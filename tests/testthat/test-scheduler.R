test_that("leitner moves boxes and intervals", {
  d <- as.Date("2026-01-01")
  s <- new_state()
  s <- next_due(s, list(correct = TRUE, rating = "easy"), "leitner", d)
  expect_equal(s$box, 2L); expect_equal(s$due, d + 1)
  s <- next_due(s, list(correct = TRUE, rating = "easy"), "leitner", d)
  expect_equal(s$due, d + 3)
  s <- next_due(s, list(correct = FALSE), "leitner", d)
  expect_equal(s$box, 1L); expect_equal(s$due, d)
  for (i in 1:10) s <- next_due(s, list(correct = TRUE, rating = "easy"), "leitner", d)
  expect_equal(s$box, 5L); expect_equal(s$due, d + 21)
})

test_that("sm2 intervals grow and reset", {
  d <- as.Date("2026-01-01")
  s <- new_state()
  s <- next_due(s, list(correct = TRUE, rating = "easy"), "sm2", d)
  expect_equal(s$interval, 1)
  s <- next_due(s, list(correct = TRUE, rating = "easy"), "sm2", d)
  expect_equal(s$interval, 6)
  s <- next_due(s, list(correct = TRUE, rating = "easy"), "sm2", d)
  expect_gt(s$interval, 6)
  s <- next_due(s, list(correct = FALSE), "sm2", d)
  expect_equal(s$reps, 0L); expect_gte(s$ease, 1.3)
})
